-- 5.1 Main Complaint Details View (5-table join + SLA calculation)
CREATE OR REPLACE VIEW public.v_complaint_details AS
SELECT
  c.complaint_id,
  c.description,
  c.status,
  c.created_at,
  c.updated_at,
  s.student_id,
  s.first_name || ' ' || s.last_name                AS student_name,
  s.email                                           AS student_email,
  s.room_no,
  h.hostel_id,
  h.hostel_name,
  cat.category_id,
  cat.category_name,
  cat.sla_days,
  d.dept_id,
  d.dept_name                                       AS handling_department,
  c.created_at + (cat.sla_days * INTERVAL '1 day')   AS sla_due_at,
  (c.status <> 'Resolved'
     AND now() > c.created_at + (cat.sla_days * INTERVAL '1 day')) AS is_overdue,
  a.assigned_staff
FROM public.complaint c
JOIN public.student  s   ON s.student_id    = c.student_id
JOIN public.hostel   h   ON h.hostel_id     = s.hostel_id
JOIN public.category cat ON cat.category_id = c.category_id
JOIN public.department d ON d.dept_id       = cat.dept_id
LEFT JOIN LATERAL (
  SELECT string_agg(st.first_name || ' ' || st.last_name, ', ') AS assigned_staff
  FROM public.staff_assignment sa
  JOIN public.staff st ON st.staff_id = sa.staff_id
  WHERE sa.complaint_id = c.complaint_id
    AND sa.unassigned_at IS NULL
) a ON true;

-- 5.2 Student Summary View (Derived Total_Complaints_Filed)
CREATE OR REPLACE VIEW public.v_student_summary AS
SELECT
  s.student_id,
  s.first_name,
  s.last_name,
  s.email,
  s.room_no,
  h.hostel_name,
  COUNT(c.complaint_id)                                         AS total_complaints_filed,
  COUNT(c.complaint_id) FILTER (WHERE c.status = 'Open')        AS open_count,
  COUNT(c.complaint_id) FILTER (WHERE c.status = 'Resolved')    AS resolved_count
FROM public.student s
JOIN public.hostel h ON h.hostel_id = s.hostel_id
LEFT JOIN public.complaint c ON c.student_id = s.student_id
GROUP BY s.student_id, h.hostel_name;

-- 5.3 Staff Workload View (Aggregated active & resolved count)
CREATE OR REPLACE VIEW public.v_staff_workload AS
SELECT
  st.staff_id,
  st.first_name || ' ' || st.last_name AS staff_name,
  st.designation,
  d.dept_id,
  d.dept_name,
  COUNT(sa.assignment_id) FILTER (WHERE sa.unassigned_at IS NULL) AS active_assignments,
  COUNT(sa.assignment_id)                                          AS total_assignments
FROM public.staff st
JOIN public.department d ON d.dept_id = st.dept_id
LEFT JOIN public.staff_assignment sa ON sa.staff_id = st.staff_id
GROUP BY st.staff_id, d.dept_id, d.dept_name;

