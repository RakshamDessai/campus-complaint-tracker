-- 2.1 Department
CREATE TABLE public.department (
  dept_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dept_name  text NOT NULL UNIQUE,
  dept_head  text NOT NULL
);

-- 2.2 Staff (includes password_hash for secure authentication)
CREATE TABLE public.staff (
  staff_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     text NOT NULL,
  last_name      text NOT NULL,
  designation    text NOT NULL,
  email          text NOT NULL UNIQUE,
  dept_id        integer NOT NULL
                 REFERENCES public.department (dept_id)
                 ON UPDATE CASCADE ON DELETE RESTRICT,
  password_hash  text
);

-- 2.3 Hostel (1:1 with Staff warden)
CREATE TABLE public.hostel (
  hostel_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hostel_name  text NOT NULL UNIQUE,
  warden_id    integer NOT NULL UNIQUE
               REFERENCES public.staff (staff_id)
               ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 2.4 Student (includes password_hash for bcrypt authentication)
CREATE TABLE public.student (
  student_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     text NOT NULL,
  last_name      text NOT NULL,
  email          text NOT NULL UNIQUE,
  room_no        text NOT NULL,
  hostel_id      integer NOT NULL
                 REFERENCES public.hostel (hostel_id)
                 ON UPDATE CASCADE ON DELETE RESTRICT,
  password_hash  text
);

-- 2.5 Student_Phone (Multivalued attribute Phone_Numbers)
CREATE TABLE public.student_phone (
  student_id    integer NOT NULL
                REFERENCES public.student (student_id)
                ON UPDATE CASCADE ON DELETE CASCADE,
  phone_number  text NOT NULL,
  PRIMARY KEY (student_id, phone_number),
  CONSTRAINT chk_phone_format CHECK (phone_number ~ '^[+]?[0-9]{10,15}$')
);

-- 2.6 Category (Infrastructure, Electrical, Wi-Fi, Mess, etc.)
CREATE TABLE public.category (
  category_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name  text NOT NULL UNIQUE,
  sla_days       integer NOT NULL CHECK (sla_days > 0),
  dept_id        integer NOT NULL
                 REFERENCES public.department (dept_id)
                 ON UPDATE CASCADE ON DELETE RESTRICT
);

-- 2.7 Complaint (Core Entity)
CREATE TABLE public.complaint (
  complaint_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description   text NOT NULL,
  status        public.complaint_status NOT NULL DEFAULT 'Open',
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  student_id    integer NOT NULL
                REFERENCES public.student (student_id)
                ON UPDATE CASCADE ON DELETE RESTRICT,
  category_id   integer NOT NULL
                REFERENCES public.category (category_id)
                ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT chk_description_len CHECK (length(btrim(description)) >= 5),
  CONSTRAINT chk_updated_after_created CHECK (updated_at >= created_at)
);

-- 2.8 StatusHistory (Weak Entity identified by complaint_id + history_num)
CREATE TABLE public.status_history (
  complaint_id  integer NOT NULL
                REFERENCES public.complaint (complaint_id)
                ON UPDATE CASCADE ON DELETE CASCADE,
  history_num   integer NOT NULL CHECK (history_num > 0),
  old_status    public.complaint_status,
  new_status    public.complaint_status NOT NULL,
  status        public.complaint_status,
  changed_at    timestamptz NOT NULL DEFAULT now(),
  changed_by    text NOT NULL DEFAULT 'System',
  note          text,
  PRIMARY KEY (complaint_id, history_num)
);

-- 2.9 Staff_Assignment (N:M Junction linking Staff to Complaint)
CREATE TABLE public.staff_assignment (
  assignment_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id        integer NOT NULL
                  REFERENCES public.staff (staff_id)
                  ON UPDATE CASCADE ON DELETE RESTRICT,
  complaint_id    integer NOT NULL
                  REFERENCES public.complaint (complaint_id)
                  ON UPDATE CASCADE ON DELETE CASCADE,
  assigned_at     timestamptz NOT NULL DEFAULT now(),
  unassigned_at   timestamptz,
  CONSTRAINT chk_unassigned_after_assigned
    CHECK (unassigned_at IS NULL OR unassigned_at >= assigned_at)
);

-- 2.10 Feedback (Post-Resolution Student Rating)
CREATE TABLE public.feedback (
  feedback_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id  integer NOT NULL
                REFERENCES public.complaint (complaint_id)
                ON UPDATE CASCADE ON DELETE CASCADE,
  student_id    integer NOT NULL
                REFERENCES public.student (student_id)
                ON UPDATE CASCADE ON DELETE CASCADE,
  rating        smallint NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comments      text,
  submitted_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_feedback_complaint UNIQUE (complaint_id)
);

-- 2.11 Notification (Real-time in-app alerts)
CREATE TABLE public.notification (
