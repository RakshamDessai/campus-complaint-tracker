-- 4.1 Auto-update updated_at timestamp on complaint
CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_complaint_updated_at
  BEFORE UPDATE ON public.complaint
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- 4.2 Auto-log status transitions to status_history weak entity
CREATE OR REPLACE FUNCTION public.log_complaint_status() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_next integer;
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.status_history (complaint_id, history_num, old_status, new_status, status, changed_at, changed_by, note)
    VALUES (NEW.complaint_id, 1, NULL, NEW.status, NEW.status, NEW.created_at, 'Student', 'Complaint lodged');
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    SELECT COALESCE(MAX(h.history_num), 0) + 1
      INTO v_next
      FROM public.status_history h
     WHERE h.complaint_id = NEW.complaint_id;

    INSERT INTO public.status_history (complaint_id, history_num, old_status, new_status, status, changed_at, changed_by, note)
    VALUES (NEW.complaint_id, v_next, OLD.status, NEW.status, NEW.status, now(), 'Maintenance System', 'Status transitioned to ' || NEW.status);
  END IF;
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_complaint_status_log
  AFTER INSERT OR UPDATE OF status ON public.complaint
  FOR EACH ROW EXECUTE FUNCTION public.log_complaint_status();

-- 4.3 Assigning staff automatically transitions Open complaint to Assigned
CREATE OR REPLACE FUNCTION public.on_staff_assignment() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  UPDATE public.complaint
     SET status = 'Assigned'
   WHERE complaint_id = NEW.complaint_id
     AND status = 'Open';
  RETURN NULL;
END;
$$;

CREATE TRIGGER trg_assignment_sets_status
  AFTER INSERT ON public.staff_assignment
  FOR EACH ROW EXECUTE FUNCTION public.on_staff_assignment();

-- 4.4 SLA Escalation Stored Procedure (Can be called via RPC or scheduled job)
CREATE OR REPLACE FUNCTION public.escalate_overdue_complaints() RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
  v_count integer;
BEGIN
  WITH escalated AS (
    UPDATE public.complaint c
       SET status = 'Escalated',
           updated_at = now()
      FROM public.category cat
     WHERE cat.category_id = c.category_id
       AND c.status IN ('Open', 'Assigned', 'In-Progress')
       AND c.created_at + (cat.sla_days * INTERVAL '1 day') < now()
    RETURNING c.complaint_id
  )
  SELECT COUNT(*) INTO v_count FROM escalated;
  RETURN v_count;
END;
$$;

